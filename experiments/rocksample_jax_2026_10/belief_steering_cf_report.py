"""Pooled Markdown tables for the held-out twin belief-steering confirmation."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from experiments.rocksample_jax_2026_10.belief_steering_cf import wilson

DIRECTIONS = ("Good→Bad", "Bad→Good")
COORDINATES = ("(1,0)", "(2,1)", "(1,2)", "(2,2)", "(4,2)", "(0,3)", "(3,4)")
CHECKPOINTS = {29: "30M", 316: "330M"}


def rate(successes, n):
    low, high = wilson(successes, n)
    return f"{successes / n:.3f} [{low:.3f}, {high:.3f}]"


def pooled(reports, name):
    cells = lambda d: [r["cells"][f"{rock}|{d}|{name}"] for r in reports for rock in range(7)]
    out = []
    for d in DIRECTIONS:
        out.append(rate(sum(round(c["target"] * c["episodes"]) for c in cells(d)),
                        sum(c["episodes"] for c in cells(d))))
    both = cells(DIRECTIONS[0]) + cells(DIRECTIONS[1])
    for field in ("other_good_counts", "other_bad_counts"):
        out.append(rate(sum(c[field][0] for c in both), sum(c[field][1] for c in both)))
    for d in DIRECTIONS:
        out.append(f"{np.mean([c['mean_return'] for c in cells(d)]):.1f}")
    for d in DIRECTIONS:
        out.append(f"{np.mean([c['readout_target'] for c in cells(d)]):.2f}")
    out.append(f"{np.mean([c['checks'] for c in both]):.2f}")
    out.append(f"{np.mean([c['visit'] for c in both]):.3f}")
    out.append(f"{np.mean([c['exit'] for c in both]):.3f}")
    return out


def matrix(reports, direction, name):
    field = "picked_good_by_rock" if direction == "Good→Bad" else "picked_bad_by_rock"
    counts = np.zeros((2, 7, 7))
    for r in reports:
        for rock in range(7):
            counts[:, rock] += np.asarray(r["cells"][f"{rock}|{direction}|{name}"][field])
    return counts[0] / counts[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    args = parser.parse_args()
    lines = ["# Held-out twin belief-steering tables", "",
             "Generated by `belief_steering_cf_report.py`. Rates are pooled over seven target",
             "rocks and the listed agents with Wilson 95% intervals. G→B: the target rock is",
             "Good and is steered towards Bad; B→G: the reverse. Returns and decoded target",
             "beliefs are means over target rocks.", ""]
    header = ("| Variant | Target sampled, G→B | Target sampled, B→G | Other Good sampled | "
              "Other Bad sampled | Return G→B | Return B→G | Decoded target G→B | "
              "Decoded target B→G | Target checks | Target visited | Exited |")
    for update, label in CHECKPOINTS.items():
        reports = [json.loads((args.directory / f"agent{a}_update{update}.json").read_text())
                   for a in range(3)]
        names = [k.split("|")[2] for k in reports[0]["cells"] if k.startswith("0|Good→Bad|")]
        for title, group in ((f"{label} checkpoints, three agents pooled", reports),
                             *((f"{label} checkpoint, agent {a}", [r]) for a, r in enumerate(reports))):
            lines += [f"## {title}", "", header, "|" + " --- |" * 12]
            for name in names if len(group) > 1 else ("intact", "steer", "control", "legacy_clamp"):
                lines.append(f"| `{name}` | " + " | ".join(pooled(group, name)) + " |")
            lines.append("")
        for direction in DIRECTIONS:
            quality = "Good" if direction == "Good→Bad" else "Bad"
            lines += [f"### {label}: sampling rate of each {quality} rock under `steer` ({direction})",
                      "", "Rows: steered rock. Columns: measured rock. Three agents pooled.", "",
                      "| Steered | " + " | ".join(COORDINATES) + " |", "|" + " --- |" * 8]
            for rock, row in enumerate(matrix(reports, direction, "steer")):
                lines.append(f"| {COORDINATES[rock]} | " + " | ".join(f"{x:.3f}" for x in row) + " |")
            lines.append("")
        lines += [f"### {label}: twin-displacement fit per rock (block 1, rank 4)", "",
                  "| Agent | " + " | ".join(COORDINATES) + " |", "|" + " --- |" * 8]
        for a, r in enumerate(reports):
            lines.append(f"| {a} | " + " | ".join(
                f"{d['reflect_pca_all4_r2_site0']:.2f}" for d in r["fit"]["diagnostics"]) + " |")
        lines.append("")
    (args.directory / "tables.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
