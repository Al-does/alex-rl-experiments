"""Finite-horizon Bayesian reward analysis for targeted Cassandra maintenance.

The exact finite-horizon POMDP recursion is

    V_h(b) = max_a [b R_a + sum_z p(z | b, a) V_{h-1}(tau(b, a, z))].

Here ``z`` is the next symbol when reward is hidden and the pair
``(float32(previous_reward), next_symbol)`` when reward is observed.  An exact
enumeration of the resulting alpha vectors is intractable at horizon 1,000, so
this module reports rigorous bounds rather than mislabelling an approximation
as the optimum:

* an exact fully-observed finite-horizon MDP ceiling;
* observable-after-one-action and observable-after-next-action upper bounds;
* a feasible lower bound from executing the latter bound's action choice while
  maintaining the exact 256-state Bayesian posterior.

The reward-aware filter conditions on the reward generated by the pre-action
state before applying the transition and next-symbol likelihood.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
from typing import Any

import numpy as np

from envs.cassandra_machine.model import (
    N_COMPONENTS,
    N_CONDITIONS,
    N_OBSERVATIONS,
    N_STATES,
    OPERATE_COMPONENT_REWARD,
    TARGETED_COMPONENT_TRANSITIONS,
    TargetedAction,
    action_names,
    decode_state,
    observation_matrix,
    reward_vector,
    transition_matrix,
)


DEFAULT_HORIZON = 1_000
DEFAULT_EPISODES = 512
DEFAULT_SEED = 42
DEFAULT_TUNING_EPISODES = 128
INSPECTION_INTERVAL_GRID = (
    4,
    8,
    12,
    16,
    20,
    24,
    32,
    48,
    64,
    128,
    256,
    None,
)
_ACTION_SCOPE = "targeted"


@dataclass(frozen=True)
class TargetedModel:
    """Dense planning model plus compact reward-observation metadata."""

    transitions: np.ndarray
    observations: np.ndarray
    rewards: np.ndarray
    state_components: np.ndarray
    reward_class_by_state: np.ndarray
    reward_class_masks: np.ndarray
    component_condition_masks: np.ndarray


def build_model() -> TargetedModel:
    """Construct the exact targeted model from the shared environment tables."""

    n_actions = len(TargetedAction)
    transitions = np.stack(
        [
            transition_matrix(action, action_scope=_ACTION_SCOPE)
            for action in range(n_actions)
        ]
    )
    observations = np.stack(
        [
            observation_matrix(action, action_scope=_ACTION_SCOPE)
            for action in range(n_actions)
        ]
    )
    rewards = np.stack(
        [
            reward_vector(action, action_scope=_ACTION_SCOPE)
            for action in range(n_actions)
        ]
    )
    state_components = np.stack(
        [decode_state(state) for state in range(N_STATES)]
    )

    # The intervention exposes a float32 scalar in the observation wrapper.
    # Classify states by exactly what the learner receives, not by float64
    # products whose multiplication order can differ by a few ulps.
    _, reward_class_by_state = np.unique(
        rewards[TargetedAction.OPERATE].astype(np.float32),
        return_inverse=True,
    )
    n_reward_classes = int(reward_class_by_state.max()) + 1
    reward_class_masks = (
        reward_class_by_state[None, :] == np.arange(n_reward_classes)[:, None]
    ).astype(np.float64)
    component_condition_masks = np.stack(
        [
            np.stack(
                [
                    state_components[:, component] == condition
                    for condition in range(N_CONDITIONS)
                ]
            )
            for component in range(N_COMPONENTS)
        ]
    ).astype(np.float64)
    return TargetedModel(
        transitions=transitions,
        observations=observations,
        rewards=rewards,
        state_components=state_components,
        reward_class_by_state=reward_class_by_state,
        reward_class_masks=reward_class_masks,
        component_condition_masks=component_condition_masks,
    )


def finite_horizon_mdp_q(
    model: TargetedModel,
    horizon: int,
) -> np.ndarray:
    """Return exact undiscounted MDP Q-values indexed by remaining steps."""

    if horizon <= 0:
        raise ValueError("horizon must be positive")
    n_actions = model.rewards.shape[0]
    q_values = np.zeros(
        (horizon + 1, n_actions, N_STATES),
        dtype=np.float64,
    )
    value = np.zeros(N_STATES, dtype=np.float64)
    for remaining in range(1, horizon + 1):
        q_values[remaining] = model.rewards + np.stack(
            [
                model.transitions[action] @ value
                for action in range(n_actions)
            ]
        )
        value = q_values[remaining].max(axis=0)
    return q_values


def bayes_update(
    model: TargetedModel,
    beliefs: np.ndarray,
    actions: np.ndarray,
    observations: np.ndarray,
    *,
    observed_reward_classes: np.ndarray | None,
) -> np.ndarray:
    """Apply the exact targeted Bayesian update to a batch of histories."""

    posterior = np.empty_like(beliefs)
    for action in range(len(TargetedAction)):
        rows = np.flatnonzero(actions == action)
        if rows.size == 0:
            continue
        prior = beliefs[rows]
        if (
            observed_reward_classes is not None
            and action == TargetedAction.OPERATE
        ):
            prior = prior * model.reward_class_masks[
                observed_reward_classes[rows]
            ]
        predicted = _apply_component_transitions(
            prior,
            TARGETED_COMPONENT_TRANSITIONS[action],
        )
        likelihood = model.observations[action][
            :, observations[rows]
        ].T
        unnormalized = predicted * likelihood
        normalizer = unnormalized.sum(axis=1, keepdims=True)
        if np.any(normalizer <= 0.0):
            raise RuntimeError("Bayesian update encountered zero evidence")
        posterior[rows] = unnormalized / normalizer
    return posterior


def _apply_component_transitions(
    beliefs: np.ndarray,
    component_transitions: np.ndarray,
) -> np.ndarray:
    """Apply one factored joint transition to a batch of dense beliefs."""

    moved = beliefs.reshape((-1,) + (N_CONDITIONS,) * N_COMPONENTS)
    for component in range(N_COMPONENTS):
        axis = N_COMPONENTS - component
        last = np.moveaxis(moved, axis, -1)
        last = last @ component_transitions[component]
        moved = np.moveaxis(last, -1, axis)
    return moved.reshape((-1, N_STATES))


def observable_after_next_values(
    model: TargetedModel,
    beliefs: np.ndarray,
    next_mdp_q: np.ndarray,
    *,
    previous_reward_observed: bool,
) -> np.ndarray:
    """Score actions after one real observation, then grant full observability.

    This is an upper-bound backup: after the selected action and one further
    posterior-dependent action, the state is treated as fully observed.  Its
    greedy action is nevertheless feasible when repeatedly recomputed from the
    real posterior, making the simulated return a valid lower bound.
    """

    values = beliefs @ model.rewards.T
    n_actions = len(TargetedAction)
    for action in range(n_actions):
        possible_observations = np.flatnonzero(
            model.observations[action].sum(axis=0) > 0.0
        )
        coefficient_blocks: list[np.ndarray] = []
        for observation in possible_observations:
            weighted_next_q = (
                model.observations[action, :, observation, None]
                * next_mdp_q.T
            )
            # Shape: continuation action x current state.
            coefficients = (
                model.transitions[action] @ weighted_next_q
            ).T
            if (
                previous_reward_observed
                and action == TargetedAction.OPERATE
            ):
                coefficient_blocks.extend(
                    coefficients * reward_mask
                    for reward_mask in model.reward_class_masks
                )
            else:
                coefficient_blocks.append(coefficients)
        stacked = np.stack(coefficient_blocks)
        scores = beliefs @ stacked.reshape((-1, N_STATES)).T
        scores = scores.reshape(
            beliefs.shape[0],
            len(coefficient_blocks),
            n_actions,
        )
        values[:, action] += scores.max(axis=2).sum(axis=1)
    return values


def fully_observed_summary(
    model: TargetedModel,
    mdp_q: np.ndarray,
    horizon: int,
) -> dict[str, Any]:
    """Propagate the exact occupancy of the finite-horizon MDP policy."""

    distribution = np.full(N_STATES, 1.0 / N_STATES)
    action_mass = np.zeros(len(TargetedAction), dtype=np.float64)
    expected_return = 0.0
    for remaining in range(horizon, 0, -1):
        policy = mdp_q[remaining].argmax(axis=0)
        expected_return += float(
            np.sum(
                distribution
                * model.rewards[policy, np.arange(N_STATES)]
            )
        )
        next_distribution = np.zeros(N_STATES, dtype=np.float64)
        for action in range(len(TargetedAction)):
            state_mask = policy == action
            mass = distribution * state_mask
            action_mass[action] += mass.sum()
            next_distribution += mass @ model.transitions[action]
        distribution = next_distribution
    return {
        "expected_return": expected_return,
        "mean_reward_per_step": expected_return / horizon,
        "expected_action_counts": _named_values(action_mass),
    }


def always_operate_summary(
    model: TargetedModel,
    horizon: int,
) -> dict[str, float]:
    """Compute the exact uniform-start return of always operating."""

    distribution = np.full(N_STATES, 1.0 / N_STATES)
    expected_return = 0.0
    for _ in range(horizon):
        expected_return += float(
            distribution @ model.rewards[TargetedAction.OPERATE]
        )
        distribution = (
            distribution @ model.transitions[TargetedAction.OPERATE]
        )
    return {
        "expected_return": expected_return,
        "mean_reward_per_step": expected_return / horizon,
    }


def simulate_bayesian_policy(
    model: TargetedModel,
    mdp_q: np.ndarray,
    *,
    horizon: int,
    episodes: int,
    seed: int,
    previous_reward_observed: bool,
    policy: str = "observable_after_next",
    inspection_interval: int | None = None,
) -> dict[str, Any]:
    """Evaluate one admissible policy driven by the exact Bayesian belief."""

    if episodes <= 1:
        raise ValueError("episodes must exceed one to estimate uncertainty")
    if policy not in {"observable_after_next", "periodic_inspection_qmdp"}:
        raise ValueError("unsupported Bayesian policy")
    if policy == "periodic_inspection_qmdp" and (
        inspection_interval is not None and inspection_interval <= 0
    ):
        raise ValueError("inspection_interval must be positive or None")
    rng = np.random.default_rng(seed)
    beliefs = np.full((episodes, N_STATES), 1.0 / N_STATES)
    components = rng.integers(
        0,
        N_CONDITIONS,
        size=(episodes, N_COMPONENTS),
        dtype=np.int8,
    )
    returns = np.zeros(episodes, dtype=np.float64)
    action_counts = np.zeros(len(TargetedAction), dtype=np.int64)
    entropy_sum = 0.0
    maintenance = {
        "repair": _empty_maintenance_accumulator(),
        "replace": _empty_maintenance_accumulator(),
    }
    steps_since_inspection = np.full(
        episodes,
        inspection_interval if inspection_interval is not None else 0,
        dtype=np.int64,
    )

    for step in range(horizon):
        remaining = horizon - step
        if policy == "observable_after_next":
            action_values = observable_after_next_values(
                model,
                beliefs,
                mdp_q[remaining - 1],
                previous_reward_observed=previous_reward_observed,
            )
        else:
            action_values = beliefs @ mdp_q[remaining].T
        actions = action_values.argmax(axis=1)
        if (
            policy == "periodic_inspection_qmdp"
            and inspection_interval is not None
            and remaining > 1
        ):
            actions[
                steps_since_inspection >= inspection_interval
            ] = TargetedAction.INSPECT
        action_counts += np.bincount(
            actions,
            minlength=len(TargetedAction),
        )
        entropy_sum += float(
            np.sum(
                -beliefs
                * np.log(np.clip(beliefs, np.finfo(np.float64).tiny, 1.0))
            )
        )

        states_before = _encode_states(components)
        rewards = model.rewards[actions, states_before]
        returns += rewards
        _accumulate_maintenance(
            model,
            beliefs,
            actions,
            action_values,
            maintenance,
        )

        components = _sample_component_transitions(
            rng,
            components,
            actions,
        )
        symbols = _sample_observations(
            rng,
            model,
            components,
            actions,
        )
        steps_since_inspection += 1
        steps_since_inspection[actions == TargetedAction.INSPECT] = 0
        if step + 1 < horizon:
            reward_classes = (
                model.reward_class_by_state[states_before]
                if previous_reward_observed
                else None
            )
            beliefs = bayes_update(
                model,
                beliefs,
                actions,
                symbols,
                observed_reward_classes=reward_classes,
            )

    standard_error = float(returns.std(ddof=1) / np.sqrt(episodes))
    return {
        "episodes": episodes,
        "seed": seed,
        "policy": policy,
        "inspection_interval": inspection_interval,
        "previous_reward_observed": previous_reward_observed,
        "return_mean": float(returns.mean()),
        "return_standard_deviation": float(returns.std(ddof=1)),
        "return_standard_error": standard_error,
        "return_95_percent_ci": [
            float(returns.mean() - 1.96 * standard_error),
            float(returns.mean() + 1.96 * standard_error),
        ],
        "return_quantiles": {
            "q05": float(np.quantile(returns, 0.05)),
            "q50": float(np.quantile(returns, 0.50)),
            "q95": float(np.quantile(returns, 0.95)),
        },
        "mean_reward_per_step": float(returns.mean() / horizon),
        "mean_belief_entropy_nats": entropy_sum / (episodes * horizon),
        "action_counts_total": _named_values(action_counts),
        "action_rates": _named_values(action_counts / (episodes * horizon)),
        "maintenance_decisions": {
            name: _finish_maintenance_accumulator(values)
            for name, values in maintenance.items()
        },
    }


def _empty_maintenance_accumulator() -> dict[str, Any]:
    return {
        "count": 0,
        "advantage_over_operate_sum": 0.0,
        "target_condition_probability_sum": np.zeros(
            N_CONDITIONS,
            dtype=np.float64,
        ),
    }


def _accumulate_maintenance(
    model: TargetedModel,
    beliefs: np.ndarray,
    actions: np.ndarray,
    action_values: np.ndarray,
    accumulators: dict[str, dict[str, Any]],
) -> None:
    for name, first_action in (
        ("repair", int(TargetedAction.REPAIR_COMPONENT_0)),
        ("replace", int(TargetedAction.REPLACE_COMPONENT_0)),
    ):
        rows = np.flatnonzero(
            (actions >= first_action)
            & (actions < first_action + N_COMPONENTS)
        )
        if rows.size == 0:
            continue
        targets = actions[rows] - first_action
        masks = model.component_condition_masks[targets]
        condition_probabilities = np.einsum(
            "bs,bcs->bc",
            beliefs[rows],
            masks,
        )
        accumulator = accumulators[name]
        accumulator["count"] += int(rows.size)
        accumulator["advantage_over_operate_sum"] += float(
            np.sum(
                action_values[rows, actions[rows]]
                - action_values[rows, TargetedAction.OPERATE]
            )
        )
        accumulator["target_condition_probability_sum"] += (
            condition_probabilities.sum(axis=0)
        )


def _finish_maintenance_accumulator(
    accumulator: dict[str, Any],
) -> dict[str, Any]:
    count = int(accumulator["count"])
    if count == 0:
        return {
            "count": 0,
            "mean_bound_advantage_over_operate": None,
            "mean_target_condition_probabilities": None,
        }
    condition_names = ("broken", "bad", "fair", "good")
    return {
        "count": count,
        "mean_bound_advantage_over_operate": (
            accumulator["advantage_over_operate_sum"] / count
        ),
        "mean_target_condition_probabilities": {
            name: float(value / count)
            for name, value in zip(
                condition_names,
                accumulator["target_condition_probability_sum"],
                strict=True,
            )
        },
    }


def _encode_states(components: np.ndarray) -> np.ndarray:
    powers = N_CONDITIONS ** np.arange(N_COMPONENTS)
    return components.astype(np.int64) @ powers


def _sample_component_transitions(
    rng: np.random.Generator,
    components: np.ndarray,
    actions: np.ndarray,
) -> np.ndarray:
    updated = components.copy()
    for component in range(N_COMPONENTS):
        rows = TARGETED_COMPONENT_TRANSITIONS[
            actions,
            component,
            components[:, component],
        ]
        draws = rng.random(components.shape[0])
        updated[:, component] = np.minimum(
            (draws[:, None] > np.cumsum(rows, axis=1)).sum(axis=1),
            N_CONDITIONS - 1,
        )
    return updated


def _sample_observations(
    rng: np.random.Generator,
    model: TargetedModel,
    components: np.ndarray,
    actions: np.ndarray,
) -> np.ndarray:
    states = _encode_states(components)
    probabilities = model.observations[actions, states]
    draws = rng.random(actions.size)
    return np.minimum(
        (draws[:, None] > np.cumsum(probabilities, axis=1)).sum(axis=1),
        N_OBSERVATIONS - 1,
    )


def idealized_break_even_operates() -> dict[str, float]:
    """Return optimistic break-even counts with the other components good."""

    quality = OPERATE_COMPONENT_REWARD
    other_good = float(quality[-1] ** (N_COMPONENTS - 1))
    good_reward = float(quality[-1] * other_good)
    bad_reward = float(quality[1] * other_good)
    fair_reward = float(quality[2] * other_good)
    return {
        "replace_broken": 3.75 / good_reward,
        "replace_bad": 3.75 / (good_reward - bad_reward),
        "replace_fair": 3.75 / (good_reward - fair_reward),
        "repair_bad": 0.75 / (0.8 * (fair_reward - bad_reward)),
        "repair_fair": 0.75 / (0.8 * (good_reward - fair_reward)),
    }


def tune_inspection_interval(
    model: TargetedModel,
    mdp_q: np.ndarray,
    *,
    horizon: int,
    episodes: int,
    seed: int,
    previous_reward_observed: bool,
) -> tuple[int | None, list[dict[str, Any]]]:
    """Select a periodic-inspection interval on a separate simulation stream."""

    records = []
    for interval in INSPECTION_INTERVAL_GRID:
        result = simulate_bayesian_policy(
            model,
            mdp_q,
            horizon=horizon,
            episodes=episodes,
            seed=seed,
            previous_reward_observed=previous_reward_observed,
            policy="periodic_inspection_qmdp",
            inspection_interval=interval,
        )
        records.append(
            {
                "inspection_interval": interval,
                "return_mean": result["return_mean"],
                "return_standard_error": result["return_standard_error"],
            }
        )
    best = max(records, key=lambda record: record["return_mean"])
    return best["inspection_interval"], records


def run_analysis(
    *,
    horizon: int,
    episodes: int,
    seed: int,
    tuning_episodes: int = DEFAULT_TUNING_EPISODES,
) -> dict[str, Any]:
    """Run both observation variants and return a JSON-serializable report."""

    model = build_model()
    mdp_q = finite_horizon_mdp_q(model, horizon)
    initial_belief = np.full((1, N_STATES), 1.0 / N_STATES)
    observable_after_one = float(
        (initial_belief @ mdp_q[horizon].T).max()
    )
    observable_after_next = {
        str(reward_observed).lower(): float(
            observable_after_next_values(
                model,
                initial_belief,
                mdp_q[horizon - 1],
                previous_reward_observed=reward_observed,
            ).max()
        )
        for reward_observed in (False, True)
    }
    evaluations = {}
    tuning = {}
    for offset, (name, reward_observed) in enumerate(
        (
            ("without_previous_reward", False),
            ("with_previous_reward", True),
        )
    ):
        best_interval, records = tune_inspection_interval(
            model,
            mdp_q,
            horizon=horizon,
            episodes=tuning_episodes,
            seed=seed + 10_000 + offset,
            previous_reward_observed=reward_observed,
        )
        tuning[name] = {
            "episodes_per_candidate": tuning_episodes,
            "seed": seed + 10_000 + offset,
            "selected_inspection_interval": best_interval,
            "candidates": records,
        }
        evaluations[name] = simulate_bayesian_policy(
            model,
            mdp_q,
            horizon=horizon,
            episodes=episodes,
            seed=seed + 20_000 + offset,
            previous_reward_observed=reward_observed,
            policy="periodic_inspection_qmdp",
            inspection_interval=best_interval,
        )
    all_good_per_step = float(OPERATE_COMPONENT_REWARD[-1] ** N_COMPONENTS)
    return {
        "analysis": "targeted Cassandra exact-belief reward analysis",
        "action_scope": _ACTION_SCOPE,
        "initial_state_distribution": "uniform",
        "horizon": horizon,
        "return_is_undiscounted": True,
        "theoretical_no_degradation_ceiling": {
            "all_good_operate_reward_per_step": all_good_per_step,
            "episode_return": horizon * all_good_per_step,
            "attainable": False,
            "reason": (
                "operate degrades each non-broken component with probability "
                "0.03 and maintenance consumes rewarded episode steps"
            ),
        },
        "exact_fully_observed_mdp": fully_observed_summary(
            model,
            mdp_q,
            horizon,
        ),
        "exact_always_operate": always_operate_summary(model, horizon),
        "pomdp_upper_bounds": {
            "state_revealed_after_first_action": observable_after_one,
            "state_revealed_after_next_action": {
                "without_previous_reward": observable_after_next["false"],
                "with_previous_reward": observable_after_next["true"],
            },
        },
        "policy_tuning": tuning,
        "feasible_exact_belief_policy": evaluations,
        "idealized_break_even_future_operates": idealized_break_even_operates(),
        "method": {
            "filter": (
                "exact 256-state Bayes posterior; reward-aware variant "
                "conditions on float32(previous_reward) before transition"
            ),
            "policy": (
                "periodic exact-belief inspection plus QMDP maintenance; "
                "inspection interval selected on separate simulation seeds"
            ),
            "optimality_statement": (
                "the exact Bayes-optimal return lies between the feasible "
                "policy return and the matching state-revelation upper bound"
            ),
        },
    }


def _named_values(values: np.ndarray) -> dict[str, float | int]:
    names = action_names(_ACTION_SCOPE)
    return {
        name: (
            int(value)
            if np.issubdtype(np.asarray(values).dtype, np.integer)
            else float(value)
        )
        for name, value in zip(names, values, strict=True)
    }


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--horizon", type=int, default=DEFAULT_HORIZON)
    parser.add_argument("--episodes", type=int, default=DEFAULT_EPISODES)
    parser.add_argument(
        "--tuning-episodes",
        type=int,
        default=DEFAULT_TUNING_EPISODES,
    )
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("results")
        / "targeted_bayesian_reward_analysis.json",
    )
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    report = run_analysis(
        horizon=args.horizon,
        episodes=args.episodes,
        seed=args.seed,
        tuning_episodes=args.tuning_episodes,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n"
    )
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
